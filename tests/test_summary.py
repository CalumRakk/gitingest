"""Test that ``gitingest.ingest()`` emits a concise local summary."""

from __future__ import annotations

import re
from pathlib import Path

from gitingest import ingest


def test_local_ingest_summary(temp_directory: Path) -> None:
    """Assert that ``gitingest.ingest()`` on a local path emits a correct summary.

    Parameters
    ----------
    temp_directory : Path
        Temporary directory structure generated by the fixture.
    """
    summary, _, _ = ingest(str(temp_directory))
    lines = summary.splitlines()
    parsed_lines = dict(line.split(": ", 1) for line in lines if ": " in line)

    # Validate keys in local scenario
    assert parsed_lines["Directory"] == "test_repo"
    assert parsed_lines["Files analyzed"] == "8"

    assert "Estimated tokens" in parsed_lines
    token_match = re.search(r"\d+", parsed_lines["Estimated tokens"])
    assert token_match, "'Estimated tokens' should contain a number"
    assert int(token_match.group()) > 0
